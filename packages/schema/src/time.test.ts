// 03-date-picker 계산 규칙 테스트: npm test -w @sprout/schema
import * as T from './time.ts'
let fail = 0
const eq = (name: string, got: unknown, want: unknown) => {
  const ok = JSON.stringify(got) === JSON.stringify(want)
  if (!ok) fail++
  console.log(ok ? 'ok  ' : 'FAIL', name, ok ? '' : `got ${JSON.stringify(got)} want ${JSON.stringify(want)}`)
}
const P = (s: string) => T.parseRule(s)!
// 2026-10-03 = 토요일
eq('daily', T.nextOccurrence(P('FREQ=DAILY'), '2026-10-03'), '2026-10-04')
eq('daily x3', T.nextOccurrence(P('FREQ=DAILY;INTERVAL=3'), '2026-10-03'), '2026-10-06')
eq('weekly same day', T.nextOccurrence(P('FREQ=WEEKLY;BYDAY=SA'), '2026-10-03'), '2026-10-10')
eq('weekdays from fri', T.nextOccurrence(P('FREQ=WEEKLY;BYDAY=MO,TU,WE,TH,FR'), '2026-10-02'), '2026-10-05')
eq('weekdays from mon', T.nextOccurrence(P('FREQ=WEEKLY;BYDAY=MO,TU,WE,TH,FR'), '2026-10-05'), '2026-10-06')
eq('biweekly mo,we from we', T.nextOccurrence(P('FREQ=WEEKLY;INTERVAL=2;BYDAY=MO,WE'), '2026-10-07'), '2026-10-19')
eq('biweekly mo,we from mo', T.nextOccurrence(P('FREQ=WEEKLY;INTERVAL=2;BYDAY=MO,WE'), '2026-10-05'), '2026-10-07')
eq('monthly 31 → nov 30', T.nextOccurrence(P('FREQ=MONTHLY;BYMONTHDAY=31'), '2026-10-31'), '2026-11-30')
eq('monthly last day', T.nextOccurrence(P('FREQ=MONTHLY;BYMONTHDAY=-1'), '2026-10-31'), '2026-11-30')
eq('monthly 3rd tue', T.nextOccurrence(P('FREQ=MONTHLY;BYDAY=3TU'), '2026-10-20'), '2026-11-17')
eq('monthly last fri', T.nextOccurrence(P('FREQ=MONTHLY;BYDAY=-1FR'), '2026-10-03'), '2026-10-30')
eq('yearly', T.nextOccurrence(P('FREQ=YEARLY;BYMONTH=1;BYMONTHDAY=20'), '2026-01-20'), '2027-01-20')
eq('until stops', T.nextOccurrence(P('FREQ=DAILY;UNTIL=20261004'), '2026-10-04'), null)
eq('count 1 stops', T.nextOccurrence(P('FREQ=DAILY;COUNT=1'), '2026-10-04'), null)
eq('count 2 continues', T.nextOccurrence(P('FREQ=DAILY;COUNT=2'), '2026-10-04'), '2026-10-05')
eq('completion weekly', T.nextOccurrence(P('FREQ=WEEKLY;BYDAY=MO'), '2026-10-08', 'completion'), '2026-10-15')
eq('rdate', T.nextOccurrence(P('RDATE=20261010,20261020'), '2026-10-10'), '2026-10-20')
eq('roundtrip', T.stringifyRule(P('FREQ=WEEKLY;INTERVAL=2;BYDAY=MO,WE;COUNT=5')), 'FREQ=WEEKLY;INTERVAL=2;BYDAY=MO,WE;COUNT=5')
eq('summary weekdays', T.ruleSummary(P('FREQ=WEEKLY;BYDAY=MO,TU,WE,TH,FR')), '평일마다')
eq('summary weekly fri', T.ruleSummary(P('FREQ=WEEKLY;BYDAY=FR')), '매주 금요일')
eq('summary 3rd tue', T.ruleSummary(P('FREQ=MONTHLY;BYDAY=3TU')), '매월 셋째 화요일')
eq('summary until', T.ruleSummary(P('FREQ=DAILY;INTERVAL=2;UNTIL=20261231')), '2일마다 · 12월 31일까지')
eq('time 1730', T.parseTimeInput('1730'), '17:30')
eq('time 930', T.parseTimeInput('930'), '09:30')
eq('time 5:30pm', T.parseTimeInput('5:30pm'), '17:30')
eq('time 5pm', T.parseTimeInput('5pm'), '17:00')
eq('time 오후 5:30', T.parseTimeInput('오후 5:30'), '17:30')
eq('time 17시 30분', T.parseTimeInput('17시 30분'), '17:30')
eq('time 12am', T.parseTimeInput('12am'), '00:00')
eq('time bad', T.parseTimeInput('25:00'), null)
// 고유어 시각(2026-10-06 사용자 "세시도 태깅이 돼야")
eq('time 세시', T.parseTimeInput('세시'), '03:00')
eq('time 오후 세시', T.parseTimeInput('오후 세시'), '15:00')
eq('time 오후 세시 반', T.parseTimeInput('오후 세시 반'), '15:30')
eq('time 열두시', T.parseTimeInput('열두시'), '12:00')
