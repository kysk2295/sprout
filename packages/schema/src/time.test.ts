eq('time 낮 열두시', T.parseTimeInput('낮 열두시'), '12:00')
eq('time 낮 두시', T.parseTimeInput('낮 두시'), '14:00')
eq('time 밤 12시 = 모호', T.parseTimeInput('밤 12시'), null)
eq('time 저녁 19시 = 겹침', T.parseTimeInput('저녁 19시'), null)
eq('time 한시간 아님', T.parseTimeInput('한시간'), null)
eq('dur -PT5M', T.durationMinutes('-PT5M'), -5)
eq('dur -P1DT15H', T.durationMinutes('-P1DT15H'), -2340)
eq('dur roundtrip', T.minutesToDuration(-2340), '-P1DT15H')
eq('dur roundtrip 0', T.minutesToDuration(0), 'PT0M')
eq('fire allday 1d before', T.dateKey(T.reminderFireTime({ due_at: '2026-10-10' }, '-PT15H')!) + ' ' + T.reminderFireTime({ due_at: '2026-10-10' }, '-PT15H')!.getHours(), '2026-10-09 9')
eq('fire timed 5m', T.fromDate(T.reminderFireTime({ due_at: '2026-10-10T17:00' }, '-PT5M')!, true), '2026-10-10T16:55')
eq('fire duration start', T.fromDate(T.reminderFireTime({ start_at: '2026-10-10T09:00', due_at: '2026-10-10T10:00' }, '-PT0M')!, true), '2026-10-10T09:00')
eq('fire duration end', T.fromDate(T.reminderFireTime({ start_at: '2026-10-10T09:00', due_at: '2026-10-10T10:00' }, 'END-PT0M')!, true), '2026-10-10T10:00')
eq('label allday custom', T.reminderLabel('-P1DT13H30M', true), '2일 전 (10:30)')
eq('label timed 45', T.reminderLabel('-PT45M', false), '45분 전')
eq('presets hint', T.repeatPresets('2026-10-20').map((p) => p.hint ?? ''), ['', '화요일', '20일', '10월 20일', '월~금'])
console.log(fail ? `${fail} FAILED` : "ALL PASS")
if (fail) process.exit(1)
