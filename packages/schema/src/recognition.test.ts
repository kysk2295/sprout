import assert from 'node:assert/strict'
import { recognize } from './recognition.ts'
const now = new Date(2026, 11, 31, 12)
assert.equal(recognize('회의 내일 오후 3시', [], [], now).due_at, '2027-01-01T15:00')
assert.equal(recognize('회의 내일 오후 3시', [], [], now).title, '회의')
assert.equal(recognize('배포 2027-02-30', [], [], now).title, '배포 2027-02-30')
assert.equal(recognize('알림 25시', [], [], now).due_at, null)
assert.equal(recognize('매일 운동', [], [], now).repeat_rule, 'FREQ=DAILY')
assert.equal(recognize('매주 월요일 운동', [], [], now).due_at, '2027-01-04')
assert.equal(recognize('다음 주 금요일 회의', [], [], now).due_at, '2027-01-08')
assert.equal(recognize('내일의 계획', [], [], now).title, '내일의 계획')
const r = recognize('기획 #업무 ~회사 !높음', [{id:'l',name:'회사'}], [{id:'t',name:'업무'}], now)
assert.deepEqual([r.title,r.list_id,r.tag_ids,r.priority], ['기획','l',['t'],3])
assert.equal(recognize('작업 #없는태그').title, '작업 #없는태그')
// E2E(2026-10-04): 요일만 쓴 '금요일 오전 10시 보고서'가 오늘 10시로 잡히던 것
assert.equal(recognize('금요일 오전 10시 보고서 제출', [], [], now).due_at, '2027-01-01T10:00')
assert.equal(recognize('금요일 오전 10시 보고서 제출', [], [], now).title, '보고서 제출')
assert.equal(recognize('목요일 회의', [], [], now).due_at, '2026-12-31')
assert.equal(recognize('월요일엔 쉬기', [], [], now).due_at, null)
// 고유어 시각 — 날짜와 같이, 강조 토큰이 말을 다 덮는다(2026-10-06)
const nat = recognize('내일 세시 반 공모전 회의', [], [], now)
assert.deepEqual([nat.due_at, nat.title], ['2027-01-01T03:30', '공모전 회의'])
assert.ok(nat.recognized.includes('세시 반'), '강조 = "세시 반" 전체')
const pmNat = recognize('내일 오후 세시 공모전', [], [], now)
assert.deepEqual([pmNat.due_at, pmNat.title, pmNat.recognized], ['2027-01-01T15:00', '공모전', ['내일', '오후 세시']])
assert.equal(recognize('저녁 일곱시 20분 운동', [], [], now).due_at, '2026-12-31T19:20')
assert.equal(recognize('모레 밤 열한시 정각 마감', [], [], now).due_at, '2027-01-02T23:00')
assert.equal(recognize('아침 열시 산책', [], [], now).title, '산책')
assert.equal(recognize('3시 반 미팅', [], [], now).due_at, '2026-12-31T03:30')
assert.equal(recognize('한시간 공부', [], [], now).due_at, null, '"한시간"은 시각이 아님')
assert.equal(recognize('세시간 운동', [], [], now).title, '세시간 운동')
assert.equal(recognize('밤 산책', [], [], now).title, '밤 산책')
console.log('recognition: 26 assertions passed')
// 47 §2.2 길잡이(비서만) — research 39 §5의 7문장 + 길이·범위. 빠른 추가는 그대로(위 '3시 반 미팅' = 03:30)
const fri = new Date(2026, 9, 9, 10) // 2026-10-09(금)
const A = (s: string) => recognize(s, [], [], fri, { assistant: true })
assert.deepEqual([A('내일 3시에 교수님 면담 잡아줘').due_at, A('내일 3시에 교수님 면담').title], ['2026-10-10T15:00', '교수님 면담'])
assert.equal(A('내일 3시에 교수님 면담').assumed_pm, true)
assert.deepEqual([A('다음 주 토요일 오후 2시로 미용실 예약').due_at, A('다음 주 토요일 오후 2시로 미용실 예약').title], ['2026-10-17T14:00', '미용실 예약'])
const meet = A('내일 오후 3시 기획 회의 한 시간')
assert.deepEqual([meet.start_at, meet.due_at, meet.duration_min, meet.title], ['2026-10-10T15:00', '2026-10-10T16:00', 60, '기획 회의'])
assert.deepEqual([A('모레 아침 9시 치과').due_at, A('모레 아침 9시 치과').title], ['2026-10-11T09:00', '치과'])
assert.deepEqual([A('매주 월요일 9시 팀 회의').due_at, A('매주 월요일 9시 팀 회의').repeat_rule], ['2026-10-12T09:00', 'FREQ=WEEKLY;BYDAY=MO'])
assert.deepEqual([A('10월 20일 보고서 제출').due_at, A('10월 20일 보고서 제출').title], ['2026-10-20', '보고서 제출'])
assert.equal(A('다음 주 수요일 7시 동아리 모임').due_at, '2026-10-14T19:00')
assert.equal(A('다음 주 수요일에 동아리').due_at, '2026-10-14')
assert.equal(A('3월 14일 결혼식').due_at, '2027-03-14', '지난 날짜는 내년')
assert.equal(A('2월 30일 회의').due_at, null)
const range = A('금요일 오후 3시부터 5시까지 스터디')
assert.deepEqual([range.start_at, range.due_at, range.title], ['2026-10-09T15:00', '2026-10-09T17:00', '스터디'])
assert.deepEqual([A('내일 2시~4시 반 리허설').start_at, A('내일 2시~4시 반 리허설').due_at], ['2026-10-10T14:00', '2026-10-10T16:30'])
assert.deepEqual([A('내일 10시 회의 1시간 반').start_at, A('내일 10시 회의 1시간 반').due_at], ['2026-10-10T10:00', '2026-10-10T11:30'])
assert.equal(A('30분 산책').duration_min, 30)
assert.equal(A('내일 아침 7시 조깅').due_at, '2026-10-10T07:00', '앞말 있으면 오전 그대로')
assert.equal(A('내일 오전 3시 배포').due_at, '2026-10-10T03:00')
assert.equal(recognize('내일 3시에 면담', [], [], fri).due_at, '2026-10-10T03:00', '빠른 추가는 오전 그대로(조사만 걷음)')
assert.equal(recognize('10월 20일 보고서', [], [], fri).due_at, '2026-10-20')
console.log('recognition (assistant): 24 assertions passed')
